const savedLanguage = document.cookie.match(/(?:^|; )bmt_player_language=(en|sk)(?:;|$)/);
let language = savedLanguage?.[1] || (navigator.language.startsWith("sk") ? "sk" : "en");

function t(text) {
  return language === "sk" && Object.hasOwn(slovak,text) ? slovak[text] : text;
}

function counted(count, singular, plural, slovakForms) {
  if (language === "en") return count + " " + (count === 1 ? singular : plural);
  const form = count === 1 ? 0 : count >= 2 && count <= 4 ? 1 : 2;
  return count + " " + slovakForms[form];
}
